'use strict';
const assert = require('node:assert/strict');
const {audit} = require('./audit-evidence-integrity');
const {firstEvidenceObservation} = require('./evidence-observation-date');
const {rankingSnapshots,firstObservedDate}=require('./build-market-public-analysis-2026');
const now = new Date('2026-09-05T12:00:00Z');
const base = {generatedAt: now.toISOString(), snapshotReferenceAt: '2026-09-05T03:00:00Z'};
const has = (result, code) => result.findings.some(f => f.code === code);
assert.equal(audit({a: base}, now).status, 'pass');
assert(has(audit({a: {...base, generatedAt: 'invalid'}}, now), 'missing_timestamp'));
assert(has(audit({a: {...base, generatedAt: '2026-09-01T03:00:00Z'}}, now), 'stale_snapshot'));
assert(has(audit({a: {...base, pendingRefresh: true}}, now), 'refresh_pending'));
assert(has(audit({a: {...base, observedPopularity: [], truth: {requestedStart: '2026-01-01', evidenceFirstObservedAt: '2026-08-29'}}}, now), 'partial_history'));
assert(has(audit({a: {...base, observedPopularity: []}}, now), 'no_unit_sales'));
assert(has(audit({a: {...base, products: [{id: 'fixture', firstPublicEvidenceAt: '2026-09-30T00:00:00Z'}]}}, now), 'future_public_evidence'));
assert(has(audit({a: {...base, products: [{id: 'fixture', window: 'after', eventDate: '2026-07-01T00:00:00Z'}]}}, now), 'outside_release_window'));
assert(has(audit({a: {...base, products: [{window: 'after', eventDate: '2026-09-04T00:00:00Z', sources: [{decisionEligible: true, discoveryOnly: true}]}]}}, now), 'no_eligible_evidence'));
assert(has(audit({a: base, b: {...base, snapshotReferenceAt: '2026-09-04T03:00:00Z'}}, now), 'mixed_snapshot_references'));
assert(has(audit({a: {...base, sourceRuns: [{id: 'fixture', ok: false}]}}, now), 'source_not_verified'));
assert(has(audit({a: {...base, sourceRuns: [{id:'a',ok:true},{id:'b',ok:false}]}}, now), 'source_coverage_below_gate'));
assert(has(audit({a: {...base, skippedSources:[{id:'a',reason:'blocked'}]}}, now), 'source_explicitly_skipped'));
const input = {a: {...base, products: []}};
const before = JSON.stringify(input);
audit(input, now);
assert.equal(JSON.stringify(input), before);
assert.equal(firstEvidenceObservation({eventDate:'2026-09-30',firstPublicEvidenceAt:'2026-09-30'},now.getTime()),null);
assert.equal(firstEvidenceObservation({eventDate:'2026-09-30',firstSeenAt:'2026-09-04T01:00:00Z'},now.getTime()),'2026-09-04T01:00:00.000Z');
assert.equal(firstEvidenceObservation({sources:[{publishedAt:'2026-09-02T00:00:00Z',observedAt:'2026-09-04T00:00:00Z'}]},now.getTime()),'2026-09-02T00:00:00.000Z');
assert.equal(firstEvidenceObservation({sources:[{publishedAt:'2026-09-30',observedAt:'invalid'}]},now.getTime()),null);
assert.equal(rankingSnapshots({updatedAt:'2025-12-31T00:00:00Z',rankings:[]}).length,0);
assert.equal(rankingSnapshots({updatedAt:'2026-09-05T00:00:00Z',rankingHistory:[{date:'2026-09-06',rows:[]},{date:'2026-02-30',rows:[]}]}).length,0);
assert.equal(firstObservedDate({analysisWindow:{firstObservedAt:'2026-01-01'}},[]),null);
console.log('Evidence integrity: 21 checks passed; fixtures are synthetic, not market evidence.');
